    /// <summary>The width of <paramref name="text"/> at <paramref name="size"/> pixels.</summary>
    /// <param name="text">The text.</param>
    /// <param name="size">The font size in pixels.</param>
    /// <returns>The width in pixels.</returns>
    public static double Width(ReadOnlySpan<char> text, double size)
    {
        var units = 0;
        var previous = -1;
        foreach (var rune in text.EnumerateRunes())
        {
            var code = rune.Value;
            units += Advance(code);
            if (previous >= 0 && code < 128)
            {
                units += Kerning[(previous * 128) + code];
            }

            previous = code < 128 ? code : -1;
        }

        return Math.Ceiling((units * size / UnitsPerEm * LayoutUnit) - 1e-9) / LayoutUnit;
    }

    private static int Advance(int code) => IsWide(code) ? (int)UnitsPerEm : code is >= 32 and <= 126 ? Ascii[code - 32] : Others.TryGetValue(code, out var advance) && advance >= 0 ? advance : Ascii['n' - 32];

    /// <summary>Whether a character is full-width in the font a browser falls back to: one em wide.</summary>
    private static bool IsWide(int code) => code is >= 0x3040 and <= 0x30FF or >= 0x3400 and <= 0x9FFF or >= 0xAC00 and <= 0xD7A3 or >= 0xFF00 and <= 0xFF60;

    private static short[] Pairs(ReadOnlySpan<int> pairs)
    {
        var table = new short[128 * 128];
        for (var i = 0; i < pairs.Length; i += 2)
        {
            table[pairs[i]] = (short)pairs[i + 1];
        }

        return table;
    }

    /// <summary>
    /// The height of a line of text at <paramref name="size"/> pixels with Inter's normal line height, as Chromium
    /// lays it out: the ascent and the descent each rounded to whole pixels.
    /// </summary>
    /// <param name="size">The font size in pixels.</param>
    /// <returns>The line height in pixels.</returns>
    public static double LineHeight(double size) => Math.Round(size * 2728 / UnitsPerEm) + Math.Round(size * 680 / UnitsPerEm);
